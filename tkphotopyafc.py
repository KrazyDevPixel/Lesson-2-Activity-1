from tkinter import *
from tkinter import messagebox
from PIL import Image, ImageTk
window=Tk()
window.title("My Photo Album")
window.config(bg='white')
window.geometry("450x500")
titlelabel=Label(window,text="My photo album",font=("arial",20,"bold"),bg="blue",fg="white",width=20)
titlelabel.pack(pady=15)
imagefile=Image.open("Different is your superpower.png")
iamgefile=imagefile.resize((300,200))
photo=ImageTk.PhotoImage(iamgefile)
imagelabel=Label(window,image=photo,bg="lavender")
imagelabel.pack(pady=10)
def showreaction():
    messagebox.showinfo("Photo Reaction","This is so nice!")
def opphode():
    detailwin=Toplevel(window)
    detailwin.title("Photo details")
    detailwin.config(bg="lightyellow")
    detailwin.geometry("350x250")
    heading=Label(detailwin,text="Photo Details",font=("arial",16,"bold"),bg="lightyellow",fg="blue")
    heading.pack(pady=15)
    details=Label(detailwin,text="Photo Name: Motivational BG. Made by: Mom. Descrtiption: My mom made this to movtivate me. :D",font=("arial",11),bg="lightyellow",justify="left")
    details.pack(pady=10)
    closebutton=Button(detailwin,text="Close",bg="purple",fg="white",command=detailwin.destroy)
reactbutton=Button(window,text="React to photo",font=("arial",12,"bold"),bg="purple",fg="white",command=showreaction)
reactbutton.pack(pady=10)
detailbutton=Button(window,text="Photo details",font=("arial",12,"bold"),bg="purple",fg="white",command=opphode)
detailbutton.pack(pady=10)
window.mainloop()
