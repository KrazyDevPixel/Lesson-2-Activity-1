from tkinter import *
window=Tk()
window.title("My profile.")
window.geometry("400x300")
title=Label(window,text="MY PROFILE",fg="white",bg="purple",width=40)
title.grid(row=0,column=0,columnspan=2,padx=10,pady=10)
namelabel=Label(window,text="Name:",fg="black",bg="white")
namelabel.grid(row=1,column=0,padx=10,pady=5)
nameentry=Entry(window,fg="blue",bg="lightyellow",width=25)
nameentry.grid(row=1,column=1,padx=10,pady=5)
hobbylabel=Label(window,text="Hobby:",fg="black",bg="white")
hobbylabel.grid(row=2,column=0,padx=10,pady=5)
hobbyentry=Entry(window,fg="blue",bg="lightyellow",width=25)
hobbyentry.grid(row=2,column=1,padx=10,pady=5)
aboutframe=Frame(window,relief=RAISED,borderwidth=3)
aboutframe.grid(row=3,column=0,columnspan=2,padx=10,pady=5)
aboutlabel=Label(aboutframe,text="About me:")
aboutlabel.pack()
abouttext=Text(aboutframe,fg="green",bg="lightyellow",width=40,height=4)
abouttext.pack()
sumbit=Button(window,text="Show my card.",fg="white",bg="purple",width=40)
sumbit.grid(row=4,column=0,columnspan=2,padx=10,pady=10)
window.mainloop()
