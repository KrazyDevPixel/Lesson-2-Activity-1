from tkinter import *
window=Tk()
window.title("Personal Bio")
window.geometry("450x450")
window.config(bg="lavender")
formframe=Frame(window,bg="White",padx=20,pady=20)
formframe.grid(row=0,column=0,padx=30,pady=30)
titlelabel=Label(formframe,text="PERSONAL BIO FORM",font=("arial",18,"bold"),bg="purple",fg="white",width=20)
titlelabel.grid(row=0,column=0,columnspan=2,pady=10)
namelabel=Label(formframe,text="Name:",font=("arial",11),bg="white")
namelabel.grid(row=1,column=0,sticky='w',pady=5)
agelabel=Label(formframe,text="Age:",font=("arial",11),bg="white")
agelabel.grid(row=2,column=0,sticky='w',pady=5)
hobbylabel=Label(formframe,text="Hobby:",font=("arial",11),bg="white")
hobbylabel.grid(row=3,column=0,sticky='w',pady=5)
aboutlabel=Label(formframe,text="About:",font=("arial",11),bg="white")
aboutlabel.grid(row=4,column=0,sticky='nw',pady=5)
nameentry=Entry(formframe,width=30)
nameentry.grid(row=1,column=1,pady=5)
ageentry=Entry(formframe,width=30)
ageentry.grid(row=2,column=1,pady=5)
hobbyentry=Entry(formframe,width=30)
hobbyentry.grid(row=3,column=1,pady=5)
aboutentry=Text(formframe,width=23,height=5)
aboutentry.grid(row=4,column=1,pady=5)
def showbio():
    name=nameentry.get()
    age=ageentry.get()
    hobby=hobbyentry.get()
    about=aboutentry.get(1.0,"END").strip()
    resultlabel.config(text="Name:"+name+"\nAge:"+age+"\nHobby:"+hobby+"\nAbout:"+about)

submitbutton=Button(formframe,text="Submit Bio",bg="purple",fg="white",font=("arial",11,"bold"),command=showbio)
submitbutton.grid(row=5,column=0,columnspan=2,pady=15)
resultlabel=Label(formframe,text="Your bio here",fg="white",bg="purple",width=35,height=5,wraplength=300,justify="left")
resultlabel.grid(row=6,column=0,columnspan=2,pady=10)
window.mainloop()